//! ChaCha12 CSPRNG registered as the `embassy-crypto` RNG driver for BLE
//! pairing keys, seeded from the nRF hardware RNG before the SoftDevice
//! Controller takes it.

use core::cell::RefCell;

use embassy_sync::blocking_mutex::{Mutex, raw::CriticalSectionRawMutex};
use rand_chacha::ChaCha12Rng;
use rand_chacha::rand_core::{RngCore as _, SeedableRng as _};

static RNG: Mutex<CriticalSectionRawMutex, RefCell<Option<ChaCha12Rng>>> =
    Mutex::new(RefCell::new(None));

pub fn seed(seed: [u8; 32]) {
    RNG.lock(|rng| rng.replace(Some(ChaCha12Rng::from_seed(seed))));
}

/// Random bytes for keys generated by the application (identity, IRK).
pub fn fill(buf: &mut [u8]) {
    <Driver as embassy_crypto::driver::Rng>::fill_bytes(buf);
}

struct Driver;

impl embassy_crypto::driver::Rng for Driver {
    fn fill_bytes(buf: &mut [u8]) {
        RNG.lock(|rng| {
            rng.borrow_mut()
                .as_mut()
                .expect("CSPRNG used before it was seeded")
                .fill_bytes(buf);
        });
    }
}

embassy_crypto::rng_impl!(Driver);

/// AES-128-CMAC (RFC 4493) for trouble's Security Manager.
///
/// `embassy-crypto-rustcrypto`'s CMAC state (`cmac::Cmac<Aes128>`) exceeds the
/// 432-byte opaque context on Cortex-M, so this driver keeps only the key and
/// the CMAC state and runs AES-128-ECB (still rustcrypto) per block. Pairing
/// MACs are short, so the per-block key schedule costs nothing noticeable.
#[allow(
    clippy::large_stack_frames,
    reason = "embassy-crypto's registration shims move its fixed 432-byte opaque context"
)]
pub mod cmac {
    use embassy_crypto::Aes128;

    #[derive(Clone)]
    pub struct State {
        key: [u8; 16],
        x: [u8; 16],
        buf: [u8; 16],
        len: usize,
    }

    impl Drop for State {
        fn drop(&mut self) {
            self.key = [0; 16];
        }
    }

    fn dbl(block: [u8; 16]) -> [u8; 16] {
        let mut out = [0u8; 16];
        let mut carry = 0u8;
        for i in (0..16).rev() {
            out[i] = (block[i] << 1) | carry;
            carry = block[i] >> 7;
        }
        if carry != 0 {
            out[15] ^= 0x87;
        }
        out
    }

    fn xor(a: &mut [u8; 16], b: &[u8; 16]) {
        for (a, b) in a.iter_mut().zip(b) {
            *a ^= b;
        }
    }

    pub fn init(key: &[u8; 16]) -> State {
        State {
            key: *key,
            x: [0; 16],
            buf: [0; 16],
            len: 0,
        }
    }

    pub fn update(state: &mut State, data: &[u8]) {
        for &byte in data {
            // A full block is processed only when more data follows: the last
            // block gets the subkey in `finalize`.
            if state.len == 16 {
                xor(&mut state.x, &state.buf);
                Aes128::new(&state.key).encrypt_block(&mut state.x);
                state.len = 0;
            }
            state.buf[state.len] = byte;
            state.len += 1;
        }
    }

    pub fn finalize(mut state: State, out: &mut [u8; 16]) {
        let aes = Aes128::new(&state.key);
        let mut l = [0u8; 16];
        aes.encrypt_block(&mut l);
        let k1 = dbl(l);
        let mut last = state.buf;
        if state.len == 16 {
            xor(&mut last, &k1);
        } else {
            last[state.len] = 0x80;
            last[state.len + 1..].fill(0);
            xor(&mut last, &dbl(k1));
        }
        xor(&mut state.x, &last);
        aes.encrypt_block(&mut state.x);
        *out = state.x;
    }

    pub fn reset(state: &mut State) {
        state.x = [0; 16];
        state.buf = [0; 16];
        state.len = 0;
    }

    struct Driver;

    impl embassy_crypto::driver::Aes128Cmac for Driver {
        type Context = State;

        fn init(key: &[u8; 16]) -> State {
            init(key)
        }

        fn update(ctx: &mut State, data: &[u8]) {
            update(ctx, data);
        }

        fn finalize(ctx: State, out: &mut [u8; 16]) {
            finalize(ctx, out);
        }

        fn reset(ctx: &mut State) {
            reset(ctx);
        }
    }

    embassy_crypto::aes128_cmac_impl!(Driver);

    /// RFC 4493 examples 1 and 2 (empty and one-block messages).
    pub fn self_test() -> bool {
        const KEY: [u8; 16] = [
            0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf,
            0x4f, 0x3c,
        ];
        const MSG: [u8; 16] = [
            0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93,
            0x17, 0x2a,
        ];
        const EMPTY_TAG: [u8; 16] = [
            0xbb, 0x1d, 0x69, 0x29, 0xe9, 0x59, 0x37, 0x28, 0x7f, 0xa3, 0x7d, 0x12, 0x9b, 0x75,
            0x67, 0x46,
        ];
        const MSG_TAG: [u8; 16] = [
            0x07, 0x0a, 0x16, 0xb4, 0x6b, 0x4d, 0x41, 0x44, 0xf7, 0x9b, 0xdd, 0x9d, 0xd0, 0x4a,
            0x28, 0x7c,
        ];
        let mut tag = [0u8; 16];
        finalize(init(&KEY), &mut tag);
        let empty_ok = tag == EMPTY_TAG;
        let mut state = init(&KEY);
        update(&mut state, &MSG);
        finalize(state, &mut tag);
        empty_ok && tag == MSG_TAG
    }
}

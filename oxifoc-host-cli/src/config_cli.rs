//! Config CLI: the generic group schema + read-modify-write live in
//! `oxifoc_host_lib::ops::config` (shared with the GUI); this module only
//! adds the CLI-only presentation — `config dump`, including the `--rust`
//! `baked_config.rs` emission.

use anyhow::Result;
use oxifoc_host_lib::HostRuntime;
use serde_json::Value;

// Re-export the shared, presentation-agnostic config ops so existing call
// sites (`config_cli::parse_group`, `config_cli::current_value`, …) and the
// `detect` module keep working unchanged.
use oxifoc_host_lib::ops::config::write_from_value;
pub use oxifoc_host_lib::ops::config::{
    GROUPS, config_snapshot, current_value, group_value, parse_group, read_group, set_fields,
};

/// Dump every config group; `--rust` renders a ready-to-paste
/// `baked_config.rs` body for the baked firmware profile.
pub fn dump_config(runtime: &HostRuntime, rust: bool, json_mode: bool) -> Result<()> {
    let cmd = &runtime.cmd_tx;
    if json_mode && !rust {
        let mut obj = serde_json::Map::new();
        for (name, group) in GROUPS {
            let snapshot = read_group(cmd, group)?;
            if !snapshot.valid {
                anyhow::bail!("invalid stored calibration: {name}");
            }
            let v = snapshot
                .value
                .as_ref()
                .and_then(group_value)
                .unwrap_or(Value::Null);
            obj.insert(name.to_string(), v);
        }
        println!("{:#}", Value::Object(obj));
        return Ok(());
    }

    let mut read = Vec::new();
    for (_, g) in GROUPS {
        let snapshot = read_group(cmd, g)?;
        if !snapshot.valid {
            anyhow::bail!("invalid stored calibration: {g:?}");
        }
        read.push((g, snapshot));
    }

    if !rust {
        for (g, resp) in &read {
            match &resp.value {
                Some(value) => println!(
                    "{g:?} (revision {}, {}): {}",
                    resp.revision,
                    if resp.persisted {
                        "persisted"
                    } else {
                        "volatile"
                    },
                    group_value(value).map_or_else(|| format!("{value:?}"), |v| v.to_string())
                ),
                None => println!("{g:?} (revision {}): (not configured)", resp.revision),
            }
        }
        return Ok(());
    }

    // Rust emission: via the JSON representation so the output stays in
    // sync with the structs without per-field format strings here.
    println!("//! Compiled-in configuration for the baked profile (`storage` feature off).");
    println!("//!");
    println!("//! Generated by `oxifoc-host-cli config dump --rust`. Regenerate after");
    println!("//! re-detection or re-tuning, then rebuild and reflash.");
    println!();
    println!("use oxifoc_core::storage::*;");
    println!("use oxifoc_core::units::si;");
    println!();
    println!("/// The baked configuration.");
    println!("pub fn baked() -> RuntimeConfig {{");
    println!("    RuntimeConfig {{");
    for (name, group) in GROUPS {
        let field = name.replace('-', "_");
        let resp = read
            .iter()
            .find(|(g, _)| *g == group)
            .and_then(|(_, r)| r.value.as_ref());
        match resp.and_then(group_value) {
            Some(v) => {
                let struct_name = rust_struct_name(group);
                println!("        {field}: Some({struct_name} {{");
                if let Some(obj) = v.as_object() {
                    for (k, val) in obj {
                        println!(
                            "            {k}: {},",
                            rust_field_literal(group, &v, k, val)?
                        );
                    }
                }
                println!("        }}),");
            }
            None => println!("        {field}: None,"),
        }
    }
    println!("        board_calibration_invalid: false,");
    println!("        hall_calibration_invalid: false,");
    println!("        drive_invalid: false,");
    println!("        motor_feedback_invalid: false,");
    println!("    }}");
    println!("}}");
    Ok(())
}

fn rust_struct_name(group: oxifoc_core::types::ConfigGroupId) -> &'static str {
    use oxifoc_core::types::ConfigGroupId as G;
    // Exhaustive on purpose: a newly appended group fails to compile here
    // instead of panicking at dump time (this used to be a string match
    // ending in unreachable!()).
    match group {
        G::BoardCalibration => "BoardCalibrationConfig",
        G::MotorParams => "MotorParamsConfig",
        G::HallCalibration => "HallCalibrationConfig",
        G::DcOffsets => "DcOffsetsConfig",
        G::CurrentLimits => "CurrentLimitsConfig",
        G::VoltageLimits => "VoltageLimitsConfig",
        G::PwmConfig => "PwmConfigStored",
        G::PiGains => "PiGainsConfig",
        G::HallTuning => "HallTuningConfig",
        G::Failsafe => "FailsafeConfigStored",
        G::Velocity => "VelocityLoopConfig",
        G::Derating => "DeratingConfig",
        G::VoltageFeedforward => "VoltageFeedforwardConfig",
        G::MotorTemperature => "MotorTemperatureConfig",
        G::Drive => "DriveConfig",
        G::MotorFeedback => "MotorFeedbackConfig",
    }
}

fn rust_field_literal(
    group: oxifoc_core::types::ConfigGroupId,
    whole: &Value,
    field: &str,
    value: &Value,
) -> Result<String> {
    use oxifoc_core::types::{ConfigGroupId, VoltageFeedforwardMode};
    if group == ConfigGroupId::MotorTemperature && field == "sensor" {
        use oxifoc_core::storage::MotorTemperatureSensor;
        let sensor = serde_json::from_value::<MotorTemperatureSensor>(value.clone())?;
        return Ok(format!("MotorTemperatureSensor::{sensor:?}"));
    }
    if group == ConfigGroupId::MotorFeedback && field == "mode" {
        use oxifoc_core::storage::MotorFeedbackMode;
        let mode = serde_json::from_value::<MotorFeedbackMode>(value.clone())?;
        return Ok(format!("MotorFeedbackMode::{mode:?}"));
    }
    if group == ConfigGroupId::VoltageFeedforward && field == "mode" {
        let mode = serde_json::from_value::<VoltageFeedforwardMode>(value.clone())?;
        return Ok(match mode {
            VoltageFeedforwardMode::Disabled => "VoltageFeedforwardMode::Disabled",
            VoltageFeedforwardMode::CrossCoupling => "VoltageFeedforwardMode::CrossCoupling",
            VoltageFeedforwardMode::BackEmf => "VoltageFeedforwardMode::BackEmf",
            VoltageFeedforwardMode::Both => "VoltageFeedforwardMode::Both",
        }
        .into());
    }
    if group == ConfigGroupId::HallCalibration && field == "geometry" {
        let geometry = serde_json::from_value::<
            Option<oxifoc_core::storage::HallTransitionGeometryConfig>,
        >(value.clone())?;
        return geometry.map_or_else(
            || Ok("None".into()),
            |geometry| {
                Ok(format!(
                    "Some(HallTransitionGeometryConfig {{ entry_angles: {}, next_states: {} }})",
                    rust_literal(&serde_json::to_value(geometry.entry_angles)?),
                    rust_literal(&serde_json::to_value(geometry.next_states)?)
                ))
            },
        );
    }
    nested_literal(group, whole, &[field], value)
}

/// A field at `path` of the group's JSON, wrapped in `Some(..)`/`None` when
/// the field is an `Option` and spelled as a struct literal when it is one
/// of derating's nested structs.
fn nested_literal(
    group: oxifoc_core::types::ConfigGroupId,
    whole: &Value,
    path: &[&str],
    value: &Value,
) -> Result<String> {
    use oxifoc_core::types::ConfigGroupId;
    let optional = accepts_null(group, whole, path);
    if value.is_null() {
        anyhow::ensure!(optional, "{} is null but not optional", path.join("."));
        return Ok("None".into());
    }
    let inner = match value.as_object() {
        Some(fields) if group == ConfigGroupId::Derating => {
            let type_name = match path {
                ["speed"] => "oxifoc_core::motor::derating::SpeedDerating",
                ["modulation"] => "oxifoc_core::motor::derating::ModulationDerating",
                ["temperature"] => "oxifoc_core::motor::derating::TemperatureDerating",
                ["bus_voltage"] => "oxifoc_core::motor::derating::BusVoltageDerating",
                [_, _] => "oxifoc_core::motor::derating::Ramp",
                _ => anyhow::bail!("unexpected nested derating field {}", path.join(".")),
            };
            let fields = fields
                .iter()
                .map(|(k, v)| {
                    let mut nested = path.to_vec();
                    nested.push(k);
                    Ok(format!(
                        "{k}: {}",
                        nested_literal(group, whole, &nested, v)?
                    ))
                })
                .collect::<Result<Vec<_>>>()?
                .join(", ");
            format!("{type_name} {{ {fields} }}")
        }
        _ => rust_literal(value),
    };
    Ok(if optional {
        format!("Some({inner})")
    } else {
        inner
    })
}

/// Whether the group's typed struct still deserializes with `null` at
/// `path`, i.e. the field there is an `Option`. JSON alone cannot tell a
/// set `Option` from a plain value.
fn accepts_null(group: oxifoc_core::types::ConfigGroupId, whole: &Value, path: &[&str]) -> bool {
    let mut probe = whole.clone();
    let mut slot = &mut probe;
    for key in path {
        match slot.get_mut(*key) {
            Some(next) => slot = next,
            None => return false,
        }
    }
    *slot = Value::Null;
    write_from_value(group, probe).is_ok()
}

/// Render a JSON value as a Rust literal for baked_config emission.
fn rust_literal(v: &Value) -> String {
    match v {
        Value::Number(n) => {
            // Float fields are plain f32 or SI quantities; `si` builds
            // either from the base-unit value the JSON carries.
            if n.is_f64() {
                let f = n.as_f64().unwrap() as f32;
                format!("si({f:?})")
            } else {
                format!("{n}")
            }
        }
        Value::Bool(b) => format!("{b}"),
        Value::Array(items) => {
            let inner: Vec<String> = items.iter().map(rust_literal).collect();
            format!("[{}]", inner.join(", "))
        }
        other => format!("{other}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use oxifoc_core::types::{ConfigGroupId, VoltageFeedforwardMode};
    use oxifoc_core::units::erad;
    use oxifoc_host_lib::ops::config::group_default_value;

    #[test]
    fn baked_hall_geometry_is_a_rust_optional_struct() {
        let group = ConfigGroupId::HallCalibration;
        let whole = group_default_value(group);
        assert_eq!(
            rust_field_literal(group, &whole, "geometry", &Value::Null).unwrap(),
            "None"
        );
        let json = serde_json::to_value(oxifoc_core::storage::HallTransitionGeometryConfig {
            entry_angles: [erad(0.0); 8],
            next_states: [0; 8],
        })
        .unwrap();
        assert_eq!(
            rust_field_literal(group, &whole, "geometry", &json).unwrap(),
            "Some(HallTransitionGeometryConfig { entry_angles: [si(0.0), si(0.0), si(0.0), si(0.0), si(0.0), si(0.0), si(0.0), si(0.0)], next_states: [0, 0, 0, 0, 0, 0, 0, 0] })"
        );
        assert_eq!(
            rust_field_literal(group, &whole, "valid", &serde_json::json!([false, true])).unwrap(),
            "[false, true]"
        );
        assert!(
            rust_field_literal(
                group,
                &whole,
                "geometry",
                &serde_json::json!({"next_states": []})
            )
            .is_err()
        );
    }

    #[test]
    fn baked_feedforward_modes_are_rust_variants_instead_of_json_strings() {
        assert_eq!(
            rust_struct_name(ConfigGroupId::VoltageFeedforward),
            "VoltageFeedforwardConfig"
        );
        for mode in [
            VoltageFeedforwardMode::Disabled,
            VoltageFeedforwardMode::CrossCoupling,
            VoltageFeedforwardMode::BackEmf,
            VoltageFeedforwardMode::Both,
        ] {
            assert_eq!(
                rust_field_literal(
                    ConfigGroupId::VoltageFeedforward,
                    &group_default_value(ConfigGroupId::VoltageFeedforward),
                    "mode",
                    &serde_json::to_value(mode).unwrap()
                )
                .unwrap(),
                format!("VoltageFeedforwardMode::{mode:?}")
            );
        }
        assert!(
            rust_field_literal(
                ConfigGroupId::VoltageFeedforward,
                &group_default_value(ConfigGroupId::VoltageFeedforward),
                "mode",
                &Value::String("enabled".into())
            )
            .is_err()
        );
        assert_eq!(
            rust_literal(&serde_json::json!([1.0, 2.0])),
            "[si(1.0), si(2.0)]"
        );
    }

    #[test]
    fn baked_options_are_some_or_none() {
        let group = ConfigGroupId::CurrentLimits;
        let whole = serde_json::json!({
            "max_iq": null, "max_brake": null, "max_phase_current": 30.0,
            "bus_in_max": 5.0, "bus_regen_max": 0.0, "max_dissipation": 0.0,
        });
        let field = |name: &str| rust_field_literal(group, &whole, name, &whole[name]).unwrap();
        assert_eq!(field("max_iq"), "None");
        assert_eq!(field("max_phase_current"), "Some(si(30.0))");
        assert_eq!(field("bus_regen_max"), "Some(si(0.0))");
        assert_eq!(field("max_dissipation"), "si(0.0)", "not an Option");
    }

    #[test]
    fn baked_derating_spells_nested_structs_and_ramps() {
        let group = ConfigGroupId::Derating;
        let mut whole = group_default_value(group);
        whole["bus_voltage"]["cut"] = serde_json::json!({"start": 40.0, "end": 36.0});
        assert_eq!(
            rust_field_literal(group, &whole, "bus_voltage", &whole["bus_voltage"]).unwrap(),
            "oxifoc_core::motor::derating::BusVoltageDerating { \
             cut: Some(oxifoc_core::motor::derating::Ramp { end: si(36.0), start: si(40.0) }), \
             regen: None }"
        );
        let speed = rust_field_literal(group, &whole, "speed", &whole["speed"]).unwrap();
        assert!(speed.contains("max_forward: None"), "{speed}");
        assert!(speed.contains("speed_start_frac: si(0.8)"), "{speed}");
    }
}
